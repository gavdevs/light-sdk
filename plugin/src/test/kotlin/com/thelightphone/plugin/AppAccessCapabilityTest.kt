package com.thelightphone.plugin

import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.junit.jupiter.api.io.TempDir
import java.io.File
import java.nio.file.Path
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class AppAccessCapabilityTest {

    private fun writeToml(dir: Path, capabilities: String, permissions: String = ""): File {
        val file = dir.resolve("lighttool.toml").toFile()
        file.writeText(
            """
            [tool]
            id = "com.example.mytool"
            label = "My Tool"
            versionCode = 1
            versionName = "1.0.0"
            permissions = [$permissions]
            capabilities = [$capabilities]
            serverPackage = "com.lightos"
            """.trimIndent()
        )
        return file
    }

    @Test
    fun `app-access is a declarable capability`(@TempDir dir: Path) {
        val meta = LightToolMetadata.parse(writeToml(dir, "\"app-access\""))

        assertEquals(listOf("app-access"), meta.capabilities)
    }

    @Test
    fun `app-access requests only the permissions a tool can actually be granted`(@TempDir dir: Path) {
        val meta = LightToolMetadata.parse(writeToml(dir, "\"app-access\""))
        val xml = ManifestGenerator.render(meta)

        assertTrue(xml.contains("android.permission.REQUEST_DELETE_PACKAGES"))
        assertTrue(xml.contains("com.thelightphone.sdk.CAPABILITY_APP_ACCESS"))
    }

    @Test
    fun `app-access does not request permissions the platform never grants`(@TempDir dir: Path) {
        val meta = LightToolMetadata.parse(writeToml(dir, "\"app-access\""))
        val xml = ManifestGenerator.render(meta)

        // Enumeration is scoped by the <queries> block below, so the broad
        // QUERY_ALL_PACKAGES request would be both wider than needed and a Play
        // policy concern. BIND_* is a signature guard on the service element.
        assertFalse(xml.contains("<uses-permission android:name=\"android.permission.QUERY_ALL_PACKAGES\""))
        assertFalse(xml.contains("<uses-permission android:name=\"android.permission.BIND_NOTIFICATION_LISTENER_SERVICE\""))
    }

    @Test
    fun `the listener service is guarded by the bind permission`() {
        val xml = ManifestGenerator.render(
            LightToolMetadata(
                toolId = "com.example.mytool",
                label = "My Tool",
                versionCode = 1,
                versionName = "1.0.0",
                permissions = emptyList(),
                capabilities = listOf(LightToolPolicy.APP_ACCESS),
                serverPackage = "com.lightos",
            )
        )

        assertTrue(
            xml.contains(
                """android:permission="${LightToolPolicy.APP_ACCESS_BIND_PERMISSION}""""
            )
        )
    }

    @Test
    fun `the app-access permissions cannot be declared directly`(@TempDir dir: Path) {
        val ex = assertThrows<LightToolMetadataException> {
            LightToolMetadata.parse(
                writeToml(dir, "", permissions = "\"android.permission.REQUEST_DELETE_PACKAGES\"")
            )
        }

        assertTrue(ex.message!!.contains("generated by the 'app-access' capability"))
    }

    @Test
    fun `the listener service is only emitted for app-access tools`() {
        val withCapability = ManifestGenerator.render(
            LightToolMetadata(
                toolId = "com.example.mytool",
                label = "My Tool",
                versionCode = 1,
                versionName = "1.0.0",
                permissions = emptyList(),
                capabilities = listOf(LightToolPolicy.APP_ACCESS),
                serverPackage = "com.lightos",
            )
        )
        val withoutCapability = ManifestGenerator.render(
            LightToolMetadata(
                toolId = "com.example.mytool",
                label = "My Tool",
                versionCode = 1,
                versionName = "1.0.0",
                permissions = emptyList(),
                capabilities = emptyList(),
                serverPackage = "com.lightos",
            )
        )

        assertTrue(withCapability.contains("LightAppNotificationListener"))
        assertTrue(withCapability.contains("android.service.notification.NotificationListenerService"))
        assertFalse(withoutCapability.contains("LightAppNotificationListener"))
    }

    @Test
    fun `launcher visibility query is only emitted for app-access tools`() {
        val withCapability = ManifestGenerator.render(
            LightToolMetadata(
                toolId = "com.example.mytool",
                label = "My Tool",
                versionCode = 1,
                versionName = "1.0.0",
                permissions = emptyList(),
                capabilities = listOf(LightToolPolicy.APP_ACCESS),
                serverPackage = "com.lightos",
            )
        )
        val withoutCapability = ManifestGenerator.render(
            LightToolMetadata(
                toolId = "com.example.mytool",
                label = "My Tool",
                versionCode = 1,
                versionName = "1.0.0",
                permissions = emptyList(),
                capabilities = emptyList(),
                serverPackage = "com.lightos",
            )
        )

        assertTrue(withCapability.contains("android.intent.category.LAUNCHER"))
        // One <queries> for the SDK marker, one for launcher visibility.
        assertEquals(2, Regex("""<queries>""").findAll(withCapability).count())
        assertEquals(1, Regex("""<queries>""").findAll(withoutCapability).count())
    }
}
